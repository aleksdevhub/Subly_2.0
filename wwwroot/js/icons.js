/**
 * Заменяет заглушки вида <i data-icon="home"></i> в HTML на SVG-иконки.
 * Размер можно указать атрибутом data-size, толщину линии — data-stroke.
 */
function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => {
    el.outerHTML = icon(el.dataset.icon, Number(el.dataset.size) || 20, Number(el.dataset.stroke) || 2);
  });
}

